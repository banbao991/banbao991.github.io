const assert=require('node:assert/strict');
const {run}=require('./harness.cjs');

run(`
  replaceFarmState(newFarm());
  function visibleNaturalPlants(){
    const masks=villageWildPlantClearance();
    return VILLAGE_PROJECT_IDS.flatMap(id=>villageWildPlants(id)
      .filter(p=>villagePlantVisible(id,p,masks)).map(p=>({...p,source:id})));
  }
  function inWorkYard(p,id){const s=VILLAGE_WORK_YARDS[id];return inRect(p.x,p.y,s.left,s.top,s.right,s.bottom);}
  function completeForVegetation(id){
    Object.assign(farm.development.projects[id],{status:'complete',stage:'settle',completedAt:1});
    farm.development.completedCount++;
    farm.development.revision++;
  }
  const naturalBefore=visibleNaturalPlants();
`);
for(const id of ['lake','herbs']){
  assert.ok(run(`naturalBefore.filter(p=>inWorkYard(p,'${id}')).length`)>0,'Unbuilt yards remain natural');
}
assert.ok(run("naturalBefore.some(p=>inWorkYard(p,'herbs')&&p.source!=='herbs')"),
  'Exercise real roadside grass generated by a different project');
run("completeForVegetation('lake');completeForVegetation('herbs')");
for(const id of ['lake','herbs']){
  assert.equal(run(`visibleNaturalPlants().filter(p=>inWorkYard(p,'${id}')).length`),0,
    `${id} maintains its entire work yard, including foreign-source grass`);
}
// Finishing one work yard must not clear the rest of the undeveloped valley.
assert.ok(run("visibleNaturalPlants().filter(p=>p.source==='scenic').length")>0);
assert.ok(run("visibleNaturalPlants().filter(p=>p.source==='nursery').length")>0);
assert.equal(run("villagePlantVisible('scenic',{x:900,y:1090,seed:7})"),false);
assert.equal(run("villagePlantVisible('herbs',{x:940,y:1150,seed:9,kind:'tree'})"),false);

// Road construction clears only paving; gradual yard clearance begins afterward.
run(`replaceFarmState(newFarm());farm.development.projects.herbs.status='active'`);
assert.equal(run("villagePlantVisible('scenic',{x:940,y:1150,seed:9})"),true);
run("farm.development.projects.herbs.stage='clear'");
const remaining=[];
for(const fraction of [.3,.35,.4]){
  run(`farm.development.projects.herbs.work=VILLAGE_PROJECTS.herbs.days*VILLAGE_WORK_DAY*${fraction}`);
  remaining.push(run("visibleNaturalPlants().filter(p=>inWorkYard(p,'herbs')).length"));
}
assert.ok(remaining[0]>remaining[1]&&remaining[1]>remaining[2]);
assert.equal(remaining[2],0);

// Independent bed restoration also clears foreign-source plants only locally.
run(`replaceFarmState(newFarm());farm.nursery.beds[0].builtAt=1`);
assert.equal(run("villagePlantVisible('scenic',{...NURSERY_LAYOUT.beds[0],seed:11})"),false);

// Existing saves get the corrected layout without persisting artwork or moving actors.
run(`replaceFarmState(newFarm());completeForVegetation('lake');completeForVegetation('herbs')`);
const before=run('JSON.stringify({state:farm,runtime:captureRuntimeState()})');
run('renderCompleteFarmCanvas();drawVillageDevelopmentMiniMap()');
assert.equal(run('JSON.stringify({state:farm,runtime:captureRuntimeState()})'),before);
const saved=run('farmExportText()');
run(`importFarmText(${JSON.stringify(saved)})`);
for(const id of ['lake','herbs']){
  assert.equal(run(`visibleNaturalPlants().filter(p=>inWorkYard(p,'${id}')).length`),0);
}

// Audit every contract's buildings and ancillary maintained spaces against all
// generators. A neighboring project finishing cannot clear this project's site.
run('replaceFarmState(newFarm())');
for(const id of Array.from(run('VILLAGE_PROJECT_IDS'))){
  run(`completeForVegetation('${id}')`);
  assert.equal(run(`(()=>{
    const footprints=villageProjectPlantFootprints('${id}');
    return visibleNaturalPlants().filter(p=>footprints.some(s=>inRect(p.x,p.y,s.left,s.top,s.right,s.bottom))).length;
  })()`),0,`${id}: all facilities and maintained ancillary spaces are clear`);
}
const matureBefore=run('JSON.stringify({state:farm,runtime:captureRuntimeState()})');
run('renderCompleteFarmCanvas();drawVillageDevelopmentMiniMap()');
assert.equal(run('JSON.stringify({state:farm,runtime:captureRuntimeState()})'),matureBefore);
assert.equal(run("villagePlantVisible('donkeyRoad',{x:2232,y:1300,seed:7})"),true,
  'Road contract alone does not clear an unbuilt donkey stable');

// These are real previously missed candidates, not just synthetic anchor checks.
assert.equal(run("villagePlantVisible('scenic',{x:964,y:1834,seed:7})"),false,'Tea chair work area');
assert.equal(run("villagePlantVisible('traveller',{x:2096,y:1068,seed:7,kind:'tree'})"),false,'Dog resting yard');
assert.equal(run("villagePlantVisible('mine',{x:1930,y:1378,seed:7})"),false,'Ore cart bay');
assert.equal(run("villagePlantVisible('goats',{...PASTURE_WORKER_LAYOUT.rest,seed:7})"),false,'Sheep contract owns shared bench');
assert.equal(run("villagePlantVisible('nursery',{...NURSERY_LAYOUT.creekLookout,seed:7})"),false,'Birdwatch platform');
assert.equal(run("villagePlantVisible('mine',{x:1894,y:1613,seed:857})"),false,'Old mine ground tufts use project clearance');
assert.equal(run("villagePlantVisible('mine',{x:1620,y:1810,seed:857})"),true,'Mine peripheral meadow retained');

// Independent improvements clear only what is actually restored or purchased.
run('replaceFarmState(newFarm())');
assert.equal(run("villagePlantVisible('nursery',{x:337,y:1383,seed:7})"),true);
run("farm.nursery.beds[9].builtAt=1;farm.nursery.level=3");
assert.equal(run("villagePlantVisible('nursery',{x:337,y:1383,seed:7})"),false,'Restored bed access lane');
assert.equal(run("villagePlantVisible('nursery',{x:335,y:1400,seed:7,kind:'tree'})"),false,'Trees also avoid working lanes');
assert.equal(run("villagePlantVisible('nursery',{...NURSERY_LAYOUT.beds[5],seed:7})"),true,'Unrestored bed stays natural');
run("farm.town.improvements.catComfort.level=3");
assert.equal(run("villagePlantVisible('plaza',{...TOWN_LAYOUT.projects.catComfort,seed:7})"),false);
assert.equal(run("villagePlantVisible('plaza',{...TOWN_LAYOUT.catWater.water,seed:7})"),false);
run("completeForVegetation('herbs');farm.town.inventory.birdNest=1");
assert.equal(run("villagePlantVisible('nursery',{...TOWN_LAYOUT.birdhouse,seed:7})"),false);
run("completeForVegetation('traveller');farm.town.improvements.travellerGarden.level=1");
assert.equal(run("villagePlantVisible('donkeyRoad',{...EAST_GARDEN_EXTENSION.beds[0],seed:7})"),false);
assert.equal(run("villagePlantVisible('donkeyRoad',{...EAST_GARDEN_EXTENSION.beds[2],seed:7})"),true,'Future extension bed is not reserved bare');
run("farm.town.improvements.travellerGarden.level=3;farm.town.improvements.donkeyInn.level=3");
assert.equal(run("villagePlantVisible('donkeyRoad',{...EAST_GARDEN_EXTENSION.bench,seed:7})"),false);
assert.equal(run("villagePlantVisible('donkeyRoad',{x:2330,y:1550,seed:7})"),false,'Entire donkey pen eastern strip');
assert.equal(run("villagePlantVisible('donkeyRoad',{...TOWN_LAYOUT.donkeyInn.notice,seed:7})"),false);
console.log('development-vegetation: work yards, foreign-source clumps, gradual clearing, peripheral wilderness and save/render checks passed');
