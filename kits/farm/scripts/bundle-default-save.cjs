// Build the file:// fallback from the release ZIP; never edit the embedded bytes by hand.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');

const root = path.resolve(__dirname, '..');
const release = process.argv[2] || '1.0';
assert.match(release, /^\d+\.\d+(?:\.\d+)?$/, 'Use a numeric release such as 1.0');
const directory = path.join(root, 'saves', `v${release}`);
const archives = fs.readdirSync(directory).filter(name => /\.zip$/i.test(name));
assert.equal(archives.length, 1, 'Each default-save release must contain exactly one ZIP');
const bytes = fs.readFileSync(path.join(directory, archives[0]));
const sandbox = vm.createContext({});
vm.runInContext(fs.readFileSync(path.resolve(root, '../../libs/fflate@0.8.3/fflate.min.js'), 'utf8'), sandbox);
const files = sandbox.fflate.unzipSync(bytes);
const json = Object.keys(files).filter(name => /\.json$/i.test(name));
assert.equal(json.length, 1, 'The ZIP must contain one complete farm JSON archive');
const archive = JSON.parse(sandbox.fflate.strFromU8(files[json[0]]));
assert.equal(archive.format, 'moss-valley-farm');
assert.equal(archive.archiveVersion, 2);
assert.ok(archive.runtime);
const data = { release, day: archive.state.day, url: `saves/v${release}/${archives[0]}`, base64: bytes.toString('base64') };
fs.writeFileSync(path.join(directory, 'default-save.js'),
  "'use strict';\n// Generated by scripts/bundle-default-save.cjs from the sibling ZIP.\n"
  + '// Embedded bytes support directly opening index.html with file://.\n'
  + `const DEFAULT_FARM_SAVE = Object.freeze(${JSON.stringify(data)});\n`);
console.log(`Bundled v${release} default save: day ${data.day}, ${bytes.length} ZIP bytes.`);
